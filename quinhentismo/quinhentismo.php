            <p>O final da Idade Média (1476-1453) trouxe inovações significativas, como o uso da bússola e da pólvora, que proporcionaram aos humanos maior independência em relação às forças divinas e possibilitaram a exploração de novos territórios. Essas inovações contribuíram para as Grandes Navegações, que ocorreram nos séculos XV e XVI, quando Portugal expandiu seus domínios para a África, Ásia e América. Em 1492, Cristóvão Colombo descobriu a América, o que levou à assinatura do Tratado de Tordesilhas (1494), dividindo o Novo Mundo entre Portugal e Espanha. Em 1500, a frota portuguesa chegou ao Brasil, marcando oficialmente a descoberta do país. 

Com a chegada dos portugueses ao Brasil, surgiram duas importantes formas de produção literária: a literatura de informação, criada pelos viajantes e escrivães que acompanhavam as expedições, e a literatura de catequese, desenvolvida pelos jesuítas, que tinham a missão de converter os indígenas ao catolicismo. Esse contexto histórico marcou o início do Quinhentismo, período em que a literatura brasileira se formou a partir da combinação das práticas de exploração e evangelização. 
