            <p>As principais características do Quinhentismo podem ser agrupadas em duas vertentes: </p>
            <ul>
                <li><strong>Literatura de Informação:</strong> Composta por relatos, cartas e documentos que descrevem as terras recém-descobertas, seus recursos naturais e os habitantes nativos. O objetivo principal era informar a metrópole sobre as potencialidades do novo território. Um exemplo emblemático dessa vertente é a "Carta de Pero Vaz de Caminha", na qual o escrivão relata ao rei Dom Manuel I as características da terra e dos povos indígenas. ​  </li>
                <li><strong>Literatura de Formação ou de Catequese:</strong> Produzida pelos jesuítas com o intuito de converter os indígenas ao cristianismo, essa literatura incluía sermões, poesias e peças teatrais. José de Anchieta, por exemplo, utilizou-se de poemas e dramas em língua tupi para facilitar a compreensão e a assimilação dos ensinamentos religiosos pelos nativos. ​  </li>
